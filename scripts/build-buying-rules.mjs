#!/usr/bin/env node
// Copies the checked GOV.UK and Trading Standards rules in data/*.json into one
// browser script, so the page can use them without fetching anything.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = async (name) => JSON.parse(await readFile(resolve(ROOT, "data", name), "utf8"));

const rules = {
  sdlt: await read("sdlt-rates.json"),
  lifetimeIsa: await read("lifetime-isa.json"),
  materialInformation: await read("material-information.json"),
};

const banner = "// Generated by scripts/build-buying-rules.mjs from data/sdlt-rates.json, data/lifetime-isa.json and data/material-information.json. Do not edit by hand.\n";
await writeFile(resolve(ROOT, "buying-rules.js"), `${banner}window.WINCHESTER_BUYING_RULES = ${JSON.stringify(rules, null, 2)};\n`);
console.log("Wrote buying-rules.js");
